begin;
select plan(20);
select has_table('public','profiles','profiles table exists');
select has_table('public','sites','sites table exists');
select has_table('public','sessions','sessions table exists');
select has_table('public','reward_transactions','reward transactions table exists');
select has_table('public','audit_events','audit events table exists');
select has_column('public','sites','user_id','sites have an owner');
select has_column('public','sessions','elapsed_seconds','sessions persist elapsed time');
select has_column('public','reward_transactions','currency','transactions store currency');
select ok((select relrowsecurity from pg_class where oid='public.profiles'::regclass),'RLS enabled on profiles');
select ok((select relrowsecurity from pg_class where oid='public.sites'::regclass),'RLS enabled on sites');
select ok((select relrowsecurity from pg_class where oid='public.sessions'::regclass),'RLS enabled on sessions');
select ok((select relrowsecurity from pg_class where oid='public.reward_transactions'::regclass),'RLS enabled on reward transactions');
select ok((select relrowsecurity from pg_class where oid='public.audit_events'::regclass),'RLS enabled on audit events');
select has_function('public','start_session',array['uuid'],'session start RPC exists');
select ok(not has_function_privilege('anon','public.start_session(uuid)','EXECUTE'),'anon cannot execute start_session');
select ok(not has_function_privilege('anon','public.pause_session(uuid)','EXECUTE'),'anon cannot execute pause_session');
select ok(not has_function_privilege('anon','public.resume_session(uuid)','EXECUTE'),'anon cannot execute resume_session');
select ok(not has_function_privilege('anon','public.finish_session(uuid)','EXECUTE'),'anon cannot execute finish_session');
select ok(has_function_privilege('authenticated','public.start_session(uuid)','EXECUTE'),'authenticated can execute start_session');
select ok((select count(*)>=12 from pg_policies where schemaname='public'),'owner-scoped RLS policies exist');
select * from finish();
rollback;
